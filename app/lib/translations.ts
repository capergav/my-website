for (const loc of Object.keys(mapTranslations) as Locale[]) {
  Object.assign(translations[loc], mapTranslations[loc]);
}

export function t(key: string, locale: Locale): string {
  return translations[locale]?.[key] ?? translations.en[key] ?? key;
}

// Convenience for strings with a single {count} placeholder (e.g. the map's
// "{count} restaurants"), choosing singular/plural off the count.
export function tCount(
  n: number,
  oneKey: string,
  otherKey: string,
  locale: Locale
): string {
  const key = n === 1 ? oneKey : otherKey;
  return t(key, locale).replace("{count}", String(n));
}
